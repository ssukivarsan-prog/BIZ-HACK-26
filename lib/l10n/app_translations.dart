extension StringLocalization on String {
  /// Translates the string based on the current locale.
  /// Needs a [WidgetRef] to watch the locale provider.
  String tr(WidgetRef ref) {
    final locale = ref.watch(localeProvider);
    if (locale == 'en') return this;
    return AppTranslations.ta[this] ?? this;
  }

  /// Use this when ref is not easily available, but it won't rebuild on change automatically.
  /// Primarily for models or services. Try to use [tr] where possible.
  String trStatic(String locale) {
    if (locale == 'en') return this;
    return AppTranslations.ta[this] ?? this;
  }
}

